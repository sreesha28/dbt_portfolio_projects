




select 
    
        SILVER_LISTINGS.LISTING_ID, SILVER_LISTINGS.HOST_ID, SILVER_LISTINGS.ROOM_TYPE, SILVER_LISTINGS.PRICE_PER_NIGHT, SILVER_LISTINGS.ACCOMMODATES, SILVER_LISTINGS.BEDROOMS, 
    
        SILVER_HOSTS.HOST_NAME, SILVER_HOSTS.HOST_SINCE, SILVER_HOSTS.IS_SUPERHOST, SILVER_HOSTS.RESPONSE_RATE, SILVER_HOSTS.RESPONSE_RATE_QUALITY, 
    
        SILVER_BOOKINGS.BOOKING_ID,  SILVER_BOOKINGS.NIGHTS_BOOKED, SILVER_BOOKINGS.BOOKING_AMOUNT,SILVER_BOOKINGS.CREATED_AT
     
from SILVER.SILVER_LISTINGS as SILVER_LISTINGS

    left join SILVER.SILVER_HOSTS as SILVER_HOSTS
    on SILVER_LISTINGS.HOST_ID = SILVER_HOSTS.HOST_ID

    left join SILVER.SILVER_BOOKINGS as SILVER_BOOKINGS
    on SILVER_LISTINGS.LISTING_ID = SILVER_BOOKINGS.LISTING_ID
